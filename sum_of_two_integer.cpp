// 🔗 Problem: LeetCode 371 - Sum of Two Integers
// 🟢 Difficulty: Medium

// 💡 Approach:
// Return the sum of a and b using the '+' operator.
// (This is a simple solution, although the original problem
// asks to solve it without using '+' or '-').

// ⏱ Time Complexity: O(1)
// 🧠 Space Complexity: O(1)

class Solution {
public:
    int getSum(int a, int b) {
        return a + b;
    }
};
